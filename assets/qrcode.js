/** Encode a string (UTF-8, byte mode) into a QrCode. ecl: 'L'|'M'|'Q'|'H'. */
export function encodeText(text, eclName = 'M') {
  const bytes = Array.from(new TextEncoder().encode(String(text)));
  const ecl = ECL[eclName] || ECL.M;
  let version = 0, dataCapacityBits = 0;
  for (let v = 1; v <= 40; v++) {
    const cap = getNumDataCodewords(v, ecl.ord) * 8;
    const ccBits = v <= 9 ? 8 : 16;
    if (4 + ccBits + 8 * bytes.length <= cap) { version = v; dataCapacityBits = cap; break; }
  }
  if (!version) throw new Error('Text too long to encode in a QR code.');

  const bb = [];
  const appendBits = (val, len) => { for (let i = len - 1; i >= 0; i--) bb.push((val >>> i) & 1); };
  appendBits(0x4, 4);                                   // byte mode
  appendBits(bytes.length, version <= 9 ? 8 : 16);      // char count
  for (const b of bytes) appendBits(b, 8);
  appendBits(0, Math.min(4, dataCapacityBits - bb.length)); // terminator
  appendBits(0, (8 - (bb.length % 8)) % 8);             // pad to byte
  for (let pad = 0xec; bb.length < dataCapacityBits; pad ^= 0xec ^ 0x11) appendBits(pad, 8);

  const dataCodewords = new Array(bb.length >>> 3).fill(0);
  bb.forEach((bit, i) => { dataCodewords[i >>> 3] |= bit << (7 - (i & 7)); });

  const all = addEccAndInterleave(dataCodewords, version, ecl.ord);
  return new QrCode(version, ecl, all);
}

/** Render a QrCode to an SVG string (crisp at any size, prints fine). */
export function toSvg(qr, border = 4, light = '#ffffff', dark = '#0b1020') {
  const dim = qr.size + border * 2;
  let path = '';
  for (let y = 0; y < qr.size; y++) {
    for (let x = 0; x < qr.size; x++) {
      if (qr.getModule(x, y)) path += `M${x + border},${y + border}h1v1h-1z`;
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${dim} ${dim}" shape-rendering="crispEdges">` +
    `<rect width="${dim}" height="${dim}" fill="${light}"/>` +
    `<path d="${path}" fill="${dark}"/></svg>`;
}
